using System;
using System.Collections.Generic;
using DG.Tweening;
using UnityEngine;

namespace CapyIsland.Game
{
    /// <summary>
    /// The islands and the land bridges between them. As in the original, land is a union of
    /// circles in world units: a point is on land if it is inside any circle of an island, or of a
    /// bridge that has been opened. Every island is there from the start — visible across the water —
    /// but only reachable once a bridge joins it (Land.as, Bridge/).
    ///
    /// The world is the original's 4500 × 4500 square, with the start island's centre at Unity's
    /// origin. Island shapes and their art are generated by the island builder; this component holds
    /// the circles and answers land questions at runtime.
    /// </summary>
    public class LandMap : MonoBehaviour
    {
        /// <summary>World size, game.xml &lt;worldsize&gt;.</summary>
        public const float WorldSize = 4500f;

        /// <summary>World point at Unity's origin: the centre of the start island's rect.</summary>
        public static readonly Vector2 WorldOrigin = new Vector2(562.5f, 742.5f);

        [Serializable]
        public class Piece
        {
            public string name;
            public bool isBridge;
            public bool open;
            [Tooltip("Circles as (world x, world y, world radius).")]
            public List<Vector3> circles = new();
            [Tooltip("The rendered layers: shore, sand, grass.")]
            public List<SpriteRenderer> layers = new();
            [Tooltip("Spawn rect in world units (x, y, width, height), islands only.")]
            public List<Rect> rects = new();
        }

        public static LandMap Instance { get; private set; }

        [SerializeField] List<Piece> pieces = new();

        /// <summary>Raised when a bridge opens, with its name.</summary>
        public static event Action<string> BridgeOpened;

        public IReadOnlyList<Piece> Pieces => pieces;

        void Awake()
        {
            Instance = this;
            foreach (var p in pieces)
                if (p.isBridge)
                    foreach (var layer in p.layers)
                        if (layer != null) layer.enabled = p.open;
        }

        void OnDestroy()
        {
            if (Instance == this) Instance = null;
        }

        public void SetPieces(List<Piece> list)
        {
            pieces = list;
            _grid = null;
            _component = null;
            _walk = null;
        }

        // ---------------------------------------------------------------- coordinates

        /// <summary>A world point (y down, 4500 square) as a Unity position.</summary>
        public static Vector2 WorldToUnity(Vector2 world) =>
            new Vector2((world.x - WorldOrigin.x) * BunniSpace.UnitsPerWorld,
                        -(world.y - WorldOrigin.y) * BunniSpace.UnitsPerWorld * 0.5f);

        /// <summary>A Unity position as a world point.</summary>
        public static Vector2 UnityToWorld(Vector2 unity) =>
            new Vector2(unity.x / BunniSpace.UnitsPerWorld + WorldOrigin.x,
                        -unity.y / (BunniSpace.UnitsPerWorld * 0.5f) + WorldOrigin.y);

        // ---------------------------------------------------------------- land tests

        /// <summary>True if a Unity position is on land (any island, or an opened bridge).</summary>
        public bool IsOnLand(Vector2 unity)
        {
            var w = UnityToWorld(unity);
            var cell = Cell(w);
            if (cell == null) return false;
            foreach (var e in cell)
            {
                var piece = pieces[e.piece];
                if (piece.isBridge && !piece.open) continue;
                float dx = w.x - e.circle.x, dy = w.y - e.circle.y;
                if (dx * dx + dy * dy <= e.circle.z * e.circle.z) return true;
            }
            return false;
        }

        // ---- a coarse grid over the world, so a land test only looks at nearby circles

        struct Entry { public int piece; public int island; public Vector3 circle; }

        const float CellSize = 300f;
        const int Cells = (int)(WorldSize / CellSize) + 2;
        List<Entry>[] _grid;

        List<Entry> Cell(Vector2 world)
        {
            if (_grid == null) BuildGrid();
            int cx = Mathf.FloorToInt(world.x / CellSize), cy = Mathf.FloorToInt(world.y / CellSize);
            if (cx < 0 || cy < 0 || cx >= Cells || cy >= Cells) return null;
            return _grid[cy * Cells + cx];
        }

        void BuildGrid()
        {
            _grid = new List<Entry>[Cells * Cells];
            int island = 0;
            for (int i = 0; i < pieces.Count; i++)
            {
                var piece = pieces[i];
                foreach (var c in piece.circles)
                {
                    int x0 = Mathf.Max(0, Mathf.FloorToInt((c.x - c.z) / CellSize));
                    int x1 = Mathf.Min(Cells - 1, Mathf.FloorToInt((c.x + c.z) / CellSize));
                    int y0 = Mathf.Max(0, Mathf.FloorToInt((c.y - c.z) / CellSize));
                    int y1 = Mathf.Min(Cells - 1, Mathf.FloorToInt((c.y + c.z) / CellSize));
                    for (int y = y0; y <= y1; y++)
                    for (int x = x0; x <= x1; x++)
                    {
                        int k = y * Cells + x;
                        if (_grid[k] == null) _grid[k] = new List<Entry>();
                        _grid[k].Add(new Entry { piece = i, island = piece.isBridge ? -1 : island, circle = c });
                    }
                }
                if (!piece.isBridge) island++;
            }
        }

        /// <summary>
        /// True if a world-radius circle around a Unity position lies on land: its centre and eight
        /// points around its rim all are.
        /// </summary>
        public bool CircleOnLand(Vector2 unity, float worldRadius)
        {
            if (!IsOnLand(unity)) return false;
            var r = BunniSpace.ToUnity(new Vector2(worldRadius, worldRadius));
            for (int i = 0; i < 8; i++)
            {
                float a = i * Mathf.PI / 4f;
                if (!IsOnLand(unity + new Vector2(Mathf.Cos(a) * r.x, Mathf.Sin(a) * r.y))) return false;
            }
            return true;
        }

        /// <summary>Which island a Unity position is on, or -1 (water or a bridge).</summary>
        public int IslandAt(Vector2 unity)
        {
            var w = UnityToWorld(unity);
            var cell = Cell(w);
            if (cell == null) return -1;
            foreach (var e in cell)
            {
                if (e.island < 0) continue;
                float dx = w.x - e.circle.x, dy = w.y - e.circle.y;
                if (dx * dx + dy * dy <= e.circle.z * e.circle.z) return e.island;
            }
            return -1;
        }

        public Piece Island(int index)
        {
            int i = 0;
            foreach (var p in pieces)
            {
                if (p.isBridge) continue;
                if (i++ == index) return p;
            }
            return null;
        }

        public Piece Bridge(string name) => pieces.Find(p => p.isBridge && p.name == name);

        /// <summary>True if a bridge piece lands on the island under a Unity position.</summary>
        public bool BridgeReaches(string bridge, Vector2 unity)
        {
            var b = Bridge(bridge);
            int island = IslandAt(unity);
            return b != null && island >= 0 && Touches(b, Island(island));
        }

        public bool IsBridgeOpen(string name)
        {
            var b = Bridge(name);
            return b != null && b.open;
        }

        /// <summary>
        /// A random spot on an island where a circle of the given radius fits on clear land — the
        /// original's FindRandomCircleOnRect, used for everything a bridge or quest spawns. Falls
        /// back to the island's middle.
        /// </summary>
        public Vector2 RandomSpotOnIsland(int island, float worldRadius, int attempts = 200)
        {
            var piece = Island(island);
            if (piece == null || piece.rects.Count == 0) return Vector2.zero;
            var rect = piece.rects[0];
            for (int i = 0; i < attempts; i++)
            {
                var w = new Vector2(UnityEngine.Random.Range(rect.xMin, rect.xMax), UnityEngine.Random.Range(rect.yMin, rect.yMax));
                var u = WorldToUnity(w);
                if (IslandAt(u) != island) continue;
                if (BunniSpace.CircleOnMap(u, worldRadius)) return u;
            }
            return WorldToUnity(rect.center);
        }

        /// <summary>
        /// The middle of an island (its land circles, weighted by area), or the nearest spot to it
        /// where a circle of <paramref name="worldRadius"/> fits on the island and
        /// <paramref name="fits"/> agrees (say, nothing already standing there).
        /// </summary>
        public Vector2 SpotNearIslandMiddle(int island, float worldRadius, Func<Vector2, bool> fits = null)
        {
            var piece = Island(island);
            if (piece == null || piece.circles.Count == 0) return RandomSpotOnIsland(island, worldRadius);
            Vector2 sum = Vector2.zero;
            float weight = 0f;
            foreach (var c in piece.circles) { float a = c.z * c.z; sum += new Vector2(c.x, c.y) * a; weight += a; }
            var middle = sum / Mathf.Max(0.0001f, weight);
            bool Ok(Vector2 w)
            {
                var u = WorldToUnity(w);
                return IslandAt(u) == island && BunniSpace.CircleOnMap(u, worldRadius) && (fits == null || fits(u));
            }
            if (Ok(middle)) return WorldToUnity(middle);
            // Rings outward from the middle: the first spot that fits is the closest one.
            float step = Mathf.Max(8f, worldRadius * 0.3f);
            for (float r = step; r < 3000f; r += step)
            {
                int around = Mathf.Max(8, Mathf.RoundToInt(2f * Mathf.PI * r / step));
                for (int i = 0; i < around; i++)
                {
                    float a = i * Mathf.PI * 2f / around;
                    var w = middle + new Vector2(Mathf.Cos(a), Mathf.Sin(a)) * r;
                    if (Ok(w)) return WorldToUnity(w);
                }
            }
            return RandomSpotOnIsland(island, worldRadius);
        }

        // ---------------------------------------------------------------- bridges

        /// <summary>
        /// Opens a bridge: its land rises out of the water and becomes walkable. The original flashes
        /// the screen white and jumps the camera to it; here the land fades and swells up in place
        /// with a sparkle, and the camera glides over to show it.
        /// </summary>
        public void OpenBridge(string name, bool animate = true)
        {
            var b = Bridge(name);
            if (b == null || b.open) return;
            b.open = true;
            _component = null;
            _walk = null;

            foreach (var layer in b.layers)
            {
                if (layer == null) continue;
                layer.enabled = true;
                if (!animate) continue;
                var c = layer.color; c.a = 0f; layer.color = c;
                layer.DOFade(1f, 1.4f).SetEase(Ease.OutSine);
                var s = layer.transform.localScale;
                layer.transform.localScale = s * 0.92f;
                layer.transform.DOScale(s, 1.6f).SetEase(Ease.OutBack);
            }

            if (animate)
            {
                Sfx.Play(SfxKind.Bridge, 0.9f, 0f);
                var fx = HarvestEffects.Instance;
                if (fx != null)
                    foreach (var c in b.circles)
                        fx.Twinkle(WorldToUnity(new Vector2(c.x, c.y)), 4);
                CameraRig.CameraFocus.Show(BridgeCentre(b), 3f);
            }

            BridgeOpened?.Invoke(name);
        }

        /// <summary>
        /// True if the straight walk between two Unity positions stays on land — how the original
        /// decides a target is reachable (its paths are land-checked step by step, and a target
        /// whose way is blocked by water is marked inaccessible).
        /// </summary>
        public bool SegmentOnLand(Vector2 a, Vector2 b)
        {
            float worldLength = BunniSpace.WorldDistance(a, b);
            int steps = Mathf.Max(1, Mathf.CeilToInt(worldLength / 30f));
            for (int i = 1; i < steps; i++)
                if (!IsOnLand(Vector2.Lerp(a, b, (float)i / steps))) return false;
            return true;
        }

        int[] _component;

        // ---------------------------------------------------------------- paths

        const float PathCell = 0.5f;   // Unity units per grid cell
        bool[] _walk;
        Vector2 _walkOrigin;
        int _walkW, _walkH;

        /// <summary>
        /// A walking route over land from one Unity position to another — around bays, over open
        /// bridges — as a short list of waypoints ending at <paramref name="to"/> (or the nearest
        /// land to it). Null when there is no way there on foot.
        /// </summary>
        public List<Vector2> FindPath(Vector2 from, Vector2 to)
        {
            if (IsOnLand(to) && SegmentOnLand(from, to)) return new List<Vector2> { to };
            if (_walk == null) BuildWalk();
            int start = NearestWalkable(from), goal = NearestWalkable(to);
            if (start < 0 || goal < 0) return null;

            // A* over the grid, eight ways, no cutting corners past the water
            int n = _walk.Length;
            var cost = new float[n];
            var came = new int[n];
            for (int i = 0; i < n; i++) { cost[i] = float.MaxValue; came[i] = -1; }
            var open = new SortedSet<(float f, int i)>();
            cost[start] = 0f;
            open.Add((Heuristic(start, goal), start));
            var closed = new bool[n];
            while (open.Count > 0)
            {
                var (_, cur) = open.Min;
                open.Remove(open.Min);
                if (cur == goal) break;
                if (closed[cur]) continue;
                closed[cur] = true;
                int cx = cur % _walkW, cy = cur / _walkW;
                for (int dy = -1; dy <= 1; dy++)
                for (int dx = -1; dx <= 1; dx++)
                {
                    if (dx == 0 && dy == 0) continue;
                    int nx = cx + dx, ny = cy + dy;
                    if (nx < 0 || ny < 0 || nx >= _walkW || ny >= _walkH) continue;
                    int ni = ny * _walkW + nx;
                    if (!_walk[ni] || closed[ni]) continue;
                    if (dx != 0 && dy != 0 && (!_walk[cy * _walkW + nx] || !_walk[ny * _walkW + cx])) continue;
                    float c = cost[cur] + (dx != 0 && dy != 0 ? 1.4142f : 1f);
                    if (c >= cost[ni]) continue;
                    if (cost[ni] < float.MaxValue) open.Remove((cost[ni] + Heuristic(ni, goal), ni));
                    cost[ni] = c; came[ni] = cur;
                    open.Add((c + Heuristic(ni, goal), ni));
                }
            }
            if (start != goal && came[goal] < 0) return null;

            var cells = new List<Vector2>();
            for (int c = goal; c >= 0; c = came[c]) { cells.Add(CellCentre(c)); if (c == start) break; }
            cells.Reverse();
            cells[cells.Count - 1] = IsOnLand(to) ? to : CellCentre(goal);

            // Pull the string tight: from each point, head for the farthest one in a straight line.
            var path = new List<Vector2>();
            Vector2 at = from;
            int k = 0;
            while (k < cells.Count)
            {
                int far = k;
                for (int j = cells.Count - 1; j > k; j--) if (SegmentOnLand(at, cells[j])) { far = j; break; }
                path.Add(cells[far]);
                at = cells[far];
                k = far + 1;
            }
            return path;
        }

        float Heuristic(int a, int b)
        {
            int dx = Mathf.Abs(a % _walkW - b % _walkW), dy = Mathf.Abs(a / _walkW - b / _walkW);
            return Mathf.Max(dx, dy) + 0.4142f * Mathf.Min(dx, dy);
        }

        Vector2 CellCentre(int i) => _walkOrigin + new Vector2((i % _walkW + 0.5f) * PathCell, (i / _walkW + 0.5f) * PathCell);

        int NearestWalkable(Vector2 p)
        {
            int cx = Mathf.FloorToInt((p.x - _walkOrigin.x) / PathCell), cy = Mathf.FloorToInt((p.y - _walkOrigin.y) / PathCell);
            for (int r = 0; r <= 12; r++)
            {
                int best = -1; float bestD = float.MaxValue;
                for (int y = cy - r; y <= cy + r; y++)
                for (int x = cx - r; x <= cx + r; x++)
                {
                    if (Mathf.Max(Mathf.Abs(x - cx), Mathf.Abs(y - cy)) != r) continue;
                    if (x < 0 || y < 0 || x >= _walkW || y >= _walkH || !_walk[y * _walkW + x]) continue;
                    float d = (CellCentre(y * _walkW + x) - p).sqrMagnitude;
                    if (d < bestD) { bestD = d; best = y * _walkW + x; }
                }
                if (best >= 0) return best;
            }
            return -1;
        }

        void BuildWalk()
        {
            float minX = float.MaxValue, minY = float.MaxValue, maxX = float.MinValue, maxY = float.MinValue;
            foreach (var piece in pieces)
            foreach (var c in piece.circles)
            {
                var u = WorldToUnity(new Vector2(c.x, c.y));
                var r = BunniSpace.ToUnity(new Vector2(c.z, c.z));
                minX = Mathf.Min(minX, u.x - r.x); maxX = Mathf.Max(maxX, u.x + r.x);
                minY = Mathf.Min(minY, u.y - Mathf.Abs(r.y)); maxY = Mathf.Max(maxY, u.y + Mathf.Abs(r.y));
            }
            if (minX > maxX) { _walkW = _walkH = 1; _walk = new bool[1]; _walkOrigin = Vector2.zero; return; }
            _walkOrigin = new Vector2(minX, minY);
            _walkW = Mathf.CeilToInt((maxX - minX) / PathCell) + 1;
            _walkH = Mathf.CeilToInt((maxY - minY) / PathCell) + 1;
            _walk = new bool[_walkW * _walkH];
            for (int i = 0; i < _walk.Length; i++) _walk[i] = IsOnLand(CellCentre(i));
        }

        /// <summary>
        /// True if you can walk from one Unity position to the other: both on the same island, or
        /// on islands joined by open bridges. Workers skip targets across the water, as the
        /// original's land-checked paths do.
        /// </summary>
        public bool Reachable(Vector2 a, Vector2 b)
        {
            int ia = IslandAt(a), ib = IslandAt(b);
            if (ia < 0 || ib < 0 || ia == ib) return true;   // on a bridge: treat as connected
            if (_component == null) BuildComponents();
            return _component[ia] == _component[ib];
        }

        void BuildComponents()
        {
            int count = 0;
            foreach (var p in pieces) if (!p.isBridge) count++;
            _component = new int[count];
            for (int i = 0; i < count; i++) _component[i] = i;

            int Find(int x) { while (_component[x] != x) x = _component[x] = _component[_component[x]]; return x; }

            foreach (var bridge in pieces)
            {
                if (!bridge.isBridge || !bridge.open) continue;
                int first = -1;
                for (int island = 0; island < count; island++)
                {
                    if (!Touches(bridge, Island(island))) continue;
                    if (first < 0) first = island;
                    else _component[Find(island)] = Find(first);
                }
            }
            for (int i = 0; i < count; i++) _component[i] = Find(i);
        }

        /// <summary>
        /// The closed bridges on the shortest way from the first island to <paramref name="island"/>,
        /// or none if it is already reachable (or can't be reached by any bridge).
        /// </summary>
        public List<string> BridgesToReach(int island)
        {
            var result = new List<string>();
            int count = 0;
            foreach (var p in pieces) if (!p.isBridge) count++;
            if (island <= 0 || island >= count) return result;

            // islands joined by any bridge, open or not, remembering which bridge
            var via = new (int from, string bridge)[count];
            for (int i = 0; i < count; i++) via[i] = (-1, null);
            var seen = new bool[count];
            var queue = new Queue<int>();
            queue.Enqueue(0); seen[0] = true;
            while (queue.Count > 0)
            {
                int cur = queue.Dequeue();
                if (cur == island) break;
                foreach (var bridge in pieces)
                {
                    if (!bridge.isBridge || !Touches(bridge, Island(cur))) continue;
                    for (int next = 0; next < count; next++)
                    {
                        if (seen[next] || !Touches(bridge, Island(next))) continue;
                        seen[next] = true; via[next] = (cur, bridge.name); queue.Enqueue(next);
                    }
                }
            }
            if (!seen[island]) return result;
            for (int at = island; at > 0 && via[at].from >= 0; at = via[at].from)
                if (!IsBridgeOpen(via[at].bridge)) result.Add(via[at].bridge);
            result.Reverse();
            return result;
        }

        static bool Touches(Piece a, Piece b)
        {
            foreach (var ca in a.circles)
            foreach (var cb in b.circles)
            {
                float dx = ca.x - cb.x, dy = ca.y - cb.y, r = ca.z + cb.z;
                if (dx * dx + dy * dy < r * r) return true;
            }
            return false;
        }

        static Vector2 BridgeCentre(Piece b)
        {
            if (b.circles.Count == 0) return Vector2.zero;
            Vector2 sum = Vector2.zero;
            foreach (var c in b.circles) sum += new Vector2(c.x, c.y);
            return WorldToUnity(sum / b.circles.Count);
        }

        void OnDrawGizmosSelected()
        {
            foreach (var p in pieces)
            {
                Gizmos.color = p.isBridge ? new Color(1f, 0.8f, 0.2f, 0.6f) : new Color(0.2f, 1f, 0.4f, 0.4f);
                foreach (var c in p.circles)
                {
                    var u = WorldToUnity(new Vector2(c.x, c.y));
                    var r = BunniSpace.ToUnity(new Vector2(c.z, c.z));
                    Gizmos.DrawWireCube(u, new Vector3(r.x * 2f, r.y * 2f, 0f));
                }
            }
        }
    }
}
