using UnityEngine;

namespace CapyIsland.Game
{
    /// <summary>
    /// The island's air: what you see and hear between the things you do.
    ///
    ///  * Leaves and the odd petal drift across the view on the breeze, more when a gust comes
    ///    through; faint streaks of wind ride the gusts.
    ///  * After dark the birds fall quiet (fireflies, mist, smoke and the rest are in <see cref="Atmosphere"/>).
    ///  * Soft waves wash louder the nearer you are to the shore, and a gentle breeze rises with
    ///    each gust. Both are kept quiet and soft — a band of air, nothing hissy — so they sit
    ///    under the game rather than on top of it.
    ///  * When it rains (<see cref="Weather"/>): falling drops, little splashes on the ground and
    ///    a soft patter; afterwards, in daylight, a rainbow across the sky.
    ///  * Birds call now and then — only when there is a bird nearby, louder the closer it is.
    ///
    /// Everything follows the camera, so it costs the same however big the island is. Pure
    /// presentation, like <see cref="Wind"/>: no rule reads it. The sounds are generated by
    /// Tools/fx/sfx.mjs and sit under the master Sound switch like every other sound.
    /// </summary>
    public class Ambience : MonoBehaviour
    {
        const int SortingOrder = Bubble.SortBase - 500;   // over the island, under bubbles

        // How loud each layer gets at most (the Sound setting still mutes everything).
        const float RainVolume = 0.08f, WavesVolume = 0.09f, WindVolume = 0.035f, WindGust = 0.06f, ChirpVolume = 0.07f;

        AudioSource _waves, _wind, _rain, _chirp;
        AudioClip[] _chirps;
        ParticleSystem _leaves, _streaks, _drops, _splashes;
        SpriteRenderer _rainbow;
        float _dropDebt, _splashDebt;
        Transform _root;

        float _seaNear;          // 0 inland … 1 at the water's edge
        float _nextProbe, _nextChirp, _nextLeaf, _nextStreak;

        static readonly Color[] LeafColours =
        {
            new(0.40f, 0.66f, 0.28f), new(0.48f, 0.72f, 0.30f), new(0.36f, 0.58f, 0.25f),
            new(0.90f, 0.72f, 0.30f),   // a yellowing leaf
            new(0.96f, 0.76f, 0.82f),   // a blossom petal
        };

        void Start()
        {
            _root = new GameObject("Ambience").transform;

            _waves = Loop("Amb_Waves");
            _wind = Loop("Amb_Wind");
            _rain = Loop("Amb_Rain");
            _chirp = _root.gameObject.AddComponent<AudioSource>();
            _chirp.playOnAwake = false;
            _chirps = new[]
            {
                Resources.Load<AudioClip>("Sfx/Amb_Chirp1"), Resources.Load<AudioClip>("Sfx/Amb_Chirp2"),
                Resources.Load<AudioClip>("Sfx/Amb_Chirp3"), Resources.Load<AudioClip>("Sfx/Amb_Chirp4"),
            };

            var fx = HarvestEffects.Instance;
            _leaves = MakeSystem("AirLeaves", fx != null ? fx.LeafSprite : null, life: 7f, spin: 160f, flutter: 0.6f);
            _streaks = MakeSystem("WindStreaks", StreakSprite(), life: 1.3f, spin: 0f, flutter: 0f);
            _drops = MakeSystem("RainDrops", StreakSprite(), life: 0.5f, spin: 0f, flutter: 0f, fade: false);
            _splashes = MakeSystem("RainSplashes", UI.IconPainter.Ring, life: 0.4f, spin: 0f, flutter: 0f, grow: true);
            _rainbow = MakeRainbow();

            _nextChirp = Time.time + Random.Range(2f, 5f);
        }

        void OnDestroy()
        {
            if (_root != null) Destroy(_root.gameObject);
        }

        AudioSource Loop(string name)
        {
            var clip = Resources.Load<AudioClip>("Sfx/" + name);
            var s = _root.gameObject.AddComponent<AudioSource>();
            s.clip = clip;
            s.loop = true;
            s.volume = 0f;
            s.playOnAwake = false;
            if (clip != null) s.Play();
            return s;
        }

        void Update()
        {
            var cam = Camera.main;
            if (cam == null) return;
            var king = FindFirstObjectByType<PlayerAvatar>();
            Vector2 here = king != null ? (Vector2)king.transform.position : (Vector2)cam.transform.position;

            if (Time.unscaledTime >= _nextProbe)
            {
                _nextProbe = Time.unscaledTime + 0.3f;
                _seaNear = SeaCloseness(here);
            }
            var wind = Wind.Instance;
            float gust = wind != null ? wind.GustAt(cam.transform.position) : 0f;
            int dir = wind != null ? wind.Direction : 1;

            // Sound layers ease toward their targets, so walking to the beach swells, never jumps.
            float dt = Time.unscaledDeltaTime;
            if (_waves != null) _waves.volume = Mathf.MoveTowards(_waves.volume, WavesVolume * _seaNear * _seaNear * AudioMix.Ambience, dt * 0.1f);
            float rain = Weather.Rain;
            if (_rain != null) _rain.volume = Mathf.MoveTowards(_rain.volume, RainVolume * rain * AudioMix.Ambience, dt * 0.05f);
            if (_wind != null) _wind.volume = Mathf.MoveTowards(_wind.volume, (WindVolume + WindGust * gust) * AudioMix.Ambience, dt * 0.05f);
            Chirps();

            // Nothing drifts while the game is paused (a card or the reader is up).
            if (Time.timeScale <= 0f) return;
            Air(cam, gust, dir);
            Rain(cam, rain, dir);
            RainbowArc(cam);
        }

        // ---------------------------------------------------------------- rain

        void Rain(Camera cam, float rain, int dir)
        {
            if (rain <= 0.01f) return;
            float h = cam.orthographicSize, w = h * cam.aspect;
            Vector2 c = cam.transform.position;

            // Drops fall slantwise with the wind, from just above the view.
            _dropDebt += rain * 110f * Time.deltaTime;
            for (; _dropDebt >= 1f; _dropDebt--)
            {
                var at = new Vector2(c.x + Random.Range(-w - 2f, w + 2f), c.y + Random.Range(-h, h + 3f));
                var v = new Vector2(dir * 2.5f, -14f);
                float len = Random.Range(0.8f, 1.2f);
                Emit(_drops, at, v, new Color(0.88f, 0.94f, 1f, 0.6f), new Vector3(len, 0.11f, 1f), Mathf.Atan2(v.y, v.x) * Mathf.Rad2Deg);
            }
            // And splash where they land.
            _splashDebt += rain * 26f * Time.deltaTime;
            for (; _splashDebt >= 1f; _splashDebt--)
            {
                var at = new Vector2(c.x + Random.Range(-w, w), c.y + Random.Range(-h, h));
                Emit(_splashes, at, Vector2.zero, new Color(1f, 1f, 1f, 0.65f), new Vector3(0.5f, 0.28f, 1f), 0f);
            }
        }

        /// <summary>The rainbow after a shower: a soft arc across the top of the view, by day only.</summary>
        void RainbowArc(Camera cam)
        {
            if (_rainbow == null) return;
            float daylight = GameClock.Now == DayParts.Night ? 0f : 1f;
            float a = Weather.Rainbow * daylight * 0.3f;
            _rainbow.enabled = a > 0.005f;
            if (!_rainbow.enabled) return;
            float h = cam.orthographicSize, w = h * cam.aspect;
            var t = _rainbow.transform;
            t.position = new Vector3(cam.transform.position.x, cam.transform.position.y + h * 0.15f, 0f);
            float across = w * 2f * 1.1f / Mathf.Max(0.01f, _rainbow.sprite.bounds.size.x);
            t.localScale = new Vector3(across, across, 1f);
            _rainbow.color = new Color(1f, 1f, 1f, a);
        }

        SpriteRenderer MakeRainbow()
        {
            const int w = 256, hgt = 128;
            var tex = new Texture2D(w, hgt, TextureFormat.RGBA32, false) { wrapMode = TextureWrapMode.Clamp, hideFlags = HideFlags.DontSave };
            var px = new Color32[w * hgt];
            var bands = new[] { new Color(0.95f, 0.45f, 0.45f), new Color(0.98f, 0.7f, 0.4f), new Color(0.98f, 0.92f, 0.5f),
                                new Color(0.55f, 0.85f, 0.55f), new Color(0.5f, 0.7f, 0.95f), new Color(0.7f, 0.55f, 0.9f) };
            for (int y = 0; y < hgt; y++)
            for (int x = 0; x < w; x++)
            {
                // Distance from the arc's centre (bottom middle), as a fraction of the radius.
                float r = new Vector2(x + 0.5f - w * 0.5f, y + 0.5f).magnitude / (w * 0.5f);
                float k = Mathf.InverseLerp(0.62f, 0.98f, r);          // 0 inner edge … 1 outer edge
                if (k <= 0f || k >= 1f) continue;
                var col = bands[Mathf.Clamp(Mathf.FloorToInt((1f - k) * bands.Length), 0, bands.Length - 1)];
                float edge = Mathf.Sin(Mathf.PI * k);                  // soft at both edges
                float ends = Mathf.Clamp01(y / (hgt * 0.35f));        // fades out toward the ground
                px[y * w + x] = new Color(col.r, col.g, col.b, edge * ends);
            }
            tex.SetPixels32(px);
            tex.Apply(false, true);
            var go = new GameObject("Rainbow");
            go.transform.SetParent(_root, false);
            var sr = go.AddComponent<SpriteRenderer>();
            sr.sprite = Sprite.Create(tex, new Rect(0, 0, w, hgt), new Vector2(0.5f, 0f), 100f);
            sr.sortingOrder = SortingOrder - 1;
            sr.enabled = false;
            return sr;
        }

        // ---------------------------------------------------------------- birdsong

        /// <summary>Birds only sing when there is one about to hear.</summary>
        const float HearBirdsWithin = 14f;

        /// <summary>
        /// Birdsong comes from a real bird: the nearest one that has landed near the view. It is
        /// louder the closer it is, and sits to its side of the screen.
        /// </summary>
        void Chirps()
        {
            if (Time.time < _nextChirp || _chirps == null) return;
            _nextChirp = Time.time + 1.5f;   // check again soon if nobody is about
            if (GameClock.IsNight) return;   // the birds are asleep

            var cam = Camera.main;
            if (cam == null) return;
            Vector2 c = cam.transform.position;
            Birding.Bird nearest = null;
            float best = HearBirdsWithin;
            foreach (var bird in FindObjectsByType<Birding.Bird>(FindObjectsSortMode.None))
            {
                float d = Vector2.Distance(bird.transform.position, c);
                if (d < best) { best = d; nearest = bird; }
            }
            if (nearest == null) return;

            var clip = _chirps[Random.Range(0, _chirps.Length)];
            if (clip == null) return;
            float near = 1f - best / HearBirdsWithin;
            float halfWidth = Mathf.Max(1f, cam.orthographicSize * cam.aspect);
            _chirp.pitch = Random.Range(0.9f, 1.12f);
            _chirp.panStereo = Mathf.Clamp((nearest.transform.position.x - c.x) / halfWidth, -0.9f, 0.9f);
            _chirp.PlayOneShot(clip, ChirpVolume * Random.Range(0.75f, 1f) * near * near * AudioMix.Ambience);
            _nextChirp = Time.time + Random.Range(2.5f, 6f);
            // Sometimes it sings again straight away.
            if (Random.value < 0.3f) _nextChirp = Time.time + Random.Range(0.5f, 1.2f);
        }

        /// <summary>1 standing at the water's edge, falling to 0 about nine units inland.</summary>
        static float SeaCloseness(Vector2 at)
        {
            if (!BunniSpace.PointOnLand(at)) return 1f;
            const float reach = 9f;
            for (float r = 1f; r <= reach; r += 1f)
                for (int i = 0; i < 12; i++)
                {
                    float a = i * Mathf.PI / 6f;
                    if (!BunniSpace.PointOnLand(at + new Vector2(Mathf.Cos(a), Mathf.Sin(a)) * r))
                        return 1f - (r - 1f) / reach;
                }
            return 0f;
        }

        // ---------------------------------------------------------------- the air

        void Air(Camera cam, float gust, int dir)
        {
            float h = cam.orthographicSize, w = h * cam.aspect;
            Vector2 c = cam.transform.position;

            // Leaves: a few at a time in calm air, a flurry in a gust. They start just upwind of
            // the view and fade in, so none pops into being mid-screen.
            if (Time.time >= _nextLeaf)
            {
                _nextLeaf = Time.time + Mathf.Lerp(Random.Range(0.9f, 2.2f), Random.Range(0.15f, 0.4f), gust);
                var at = new Vector2(c.x - dir * (w + 0.5f) + Random.Range(-1f, 1f) * (gust > 0.1f ? 0f : w),
                                     c.y + Random.Range(-h, h) * 0.9f);
                var v = new Vector2(dir * Random.Range(0.9f, 1.8f) * (1f + gust * 1.6f), Random.Range(-0.35f, 0.15f));
                var colour = LeafColours[Random.Range(0, LeafColours.Length)];
                Emit(_leaves, at, v, colour, new Vector3(1f, 1f, 1f) * Random.Range(0.2f, 0.3f), Random.Range(0f, 360f));
            }

            // (Fireflies live in Atmosphere now: they blink, gather and light the grass.)

            // Wind streaks ride the gusts; in calm air only the odd wisp.
            if (Time.time >= _nextStreak)
            {
                _nextStreak = Time.time + (gust > 0.15f ? Random.Range(0.08f, 0.2f) : Random.Range(2.5f, 5f));
                var at = new Vector2(c.x + Random.Range(-w, w), c.y + Random.Range(-h, h) * 0.85f);
                float len = Random.Range(1.2f, 2.4f);
                var v = new Vector2(dir * Random.Range(5f, 8f), Random.Range(-0.2f, 0.2f));
                var tint = new Color(1f, 1f, 1f, Mathf.Lerp(0.18f, 0.4f, gust));
                Emit(_streaks, at, v, tint, new Vector3(len, len * 0.08f, 1f), 0f);
            }
        }

        static void Emit(ParticleSystem ps, Vector2 at, Vector2 velocity, Color colour, Vector3 size, float rotation)
        {
            if (ps == null) return;
            ps.Emit(new ParticleSystem.EmitParams
            {
                position = new Vector3(at.x, at.y, -0.5f),
                velocity = velocity,
                startColor = colour,
                startSize3D = size,
                rotation = rotation,
                applyShapeToPosition = false,
            }, 1);
        }

        ParticleSystem MakeSystem(string name, Sprite sprite, float life, float spin, float flutter, bool fade = true, bool grow = false)
        {
            var go = new GameObject(name);
            go.transform.SetParent(_root, false);
            var ps = go.AddComponent<ParticleSystem>();
            ps.Stop(true, ParticleSystemStopBehavior.StopEmittingAndClear);

            var main = ps.main;
            main.playOnAwake = false;
            main.loop = false;
            main.simulationSpace = ParticleSystemSimulationSpace.World;
            main.startLifetime = new ParticleSystem.MinMaxCurve(life * 0.8f, life);
            main.startSize3D = true;
            main.gravityModifier = 0f;
            main.maxParticles = 400;

            var emission = ps.emission;
            emission.enabled = false;
            var shape = ps.shape;
            shape.enabled = false;

            if (spin > 0f)
            {
                var rot = ps.rotationOverLifetime;
                rot.enabled = true;
                rot.z = new ParticleSystem.MinMaxCurve(-spin * Mathf.Deg2Rad, spin * Mathf.Deg2Rad);
            }
            if (flutter > 0f)
            {
                var noise = ps.noise;
                noise.enabled = true;
                noise.strength = flutter;
                noise.frequency = 0.5f;
                noise.scrollSpeed = 0.3f;
                noise.damping = true;
                noise.quality = ParticleSystemNoiseQuality.Low;   // WebGL
            }

            // Fade in and out, so nothing appears or vanishes in one frame (rain falls too fast to need the fade-in).
            var colour = ps.colorOverLifetime;
            colour.enabled = true;
            var g = new Gradient();
            g.SetKeys(
                new[] { new GradientColorKey(Color.white, 0f), new GradientColorKey(Color.white, 1f) },
                fade ? new[] { new GradientAlphaKey(0f, 0f), new GradientAlphaKey(1f, 0.15f), new GradientAlphaKey(1f, 0.75f), new GradientAlphaKey(0f, 1f) }
                     : new[] { new GradientAlphaKey(1f, 0f), new GradientAlphaKey(1f, 0.8f), new GradientAlphaKey(0f, 1f) });
            colour.color = g;
            if (grow)
            {
                // A splash ring widens as it fades.
                var size = ps.sizeOverLifetime;
                size.enabled = true;
                size.size = new ParticleSystem.MinMaxCurve(1f, AnimationCurve.Linear(0f, 0.3f, 1f, 1.2f));
            }

            var renderer = go.GetComponent<ParticleSystemRenderer>();
            renderer.sortingOrder = SortingOrder;
            renderer.renderMode = ParticleSystemRenderMode.Billboard;
            renderer.material = HarvestEffects.SpriteMaterial();
            if (sprite != null)
            {
                var sheet = ps.textureSheetAnimation;
                sheet.enabled = true;
                sheet.mode = ParticleSystemAnimationMode.Sprites;
                sheet.SetSprite(0, sprite);
            }
            ps.Play();
            return ps;
        }

        /// <summary>A soft round glow with a bright heart: a firefly.</summary>
        static Sprite GlowSprite()
        {
            const int n = 32;
            var tex = new Texture2D(n, n, TextureFormat.RGBA32, false) { wrapMode = TextureWrapMode.Clamp, hideFlags = HideFlags.DontSave };
            var px = new Color32[n * n];
            for (int y = 0; y < n; y++)
            for (int x = 0; x < n; x++)
            {
                float d = new Vector2(x + 0.5f - n * 0.5f, y + 0.5f - n * 0.5f).magnitude / (n * 0.5f);
                float a = Mathf.Clamp01(1f - d);
                px[y * n + x] = new Color32(255, 255, 255, (byte)(Mathf.Clamp01(a * a * 1.4f + (d < 0.25f ? 0.5f : 0f)) * 255f));
            }
            tex.SetPixels32(px);
            tex.Apply(false, true);
            return Sprite.Create(tex, new Rect(0, 0, n, n), new Vector2(0.5f, 0.5f), 100f);
        }

        /// <summary>A soft white dash, thick in the middle and thin at the ends: a breath of wind.</summary>
        static Sprite StreakSprite()
        {
            const int w = 128, h = 16;
            var tex = new Texture2D(w, h, TextureFormat.RGBA32, false) { wrapMode = TextureWrapMode.Clamp, hideFlags = HideFlags.DontSave };
            var px = new Color32[w * h];
            for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
            {
                float u = x / (w - 1f), v = (y + 0.5f) / h * 2f - 1f;
                float thick = Mathf.Sin(Mathf.PI * u) * 0.9f + 0.05f;
                float a = Mathf.Clamp01(1f - Mathf.Abs(v) / thick) * Mathf.Sin(Mathf.PI * u);
                px[y * w + x] = new Color32(255, 255, 255, (byte)(a * a * 255f));
            }
            tex.SetPixels32(px);
            tex.Apply(false, true);
            return Sprite.Create(tex, new Rect(0, 0, w, h), new Vector2(0.5f, 0.5f), 100f);
        }
    }
}
