#!/usr/bin/env node
// Generates Assets/Scripts/Game/StoreData.g.cs from the shipped balance data:
// docs/reference/store_items.xml (every store item) and docs/reference/game.xml (<stores> lists,
// <price>, <seedrates>). Data only — names, numbers, descriptions — so the game reads exactly what
// the original shipped with. Re-run after editing the XML.
//
// Usage: node Tools/data/gen_store_data.mjs

import fs from "node:fs";

const items = fs.readFileSync("docs/reference/store_items.xml", "utf8");
const game = fs.readFileSync("docs/reference/game.xml", "utf8");

const tag = (block, name) => {
  const m = block.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`));
  return m ? m[1].trim() : "";
};

// The capybara stands in for the bunni everywhere the player can see it.
const rename = (s) => s
  .replace(/Bunni House/g, "Capy House")
  .replace(/\bBunni\b/g, "Capybara")
  .replace(/\bbunnies\b/g, "capybaras")
  .replace(/\bBunnies\b/g, "Capybaras")
  .replace(/\bbunni\b/g, "capybara");

const kindOf = (cls, name) => {
  if (cls.includes("GardenItems")) return "Garden";
  if (cls.includes("ForestItems")) return "Forest";
  if (cls.includes("HillItems")) return "Hill";
  if (cls.endsWith("DeerBombItem")) return "DeerBomb";
  if (cls.endsWith("BombItem")) return "Bomb";
  if (/MillItem|MineItem/.test(cls)) return "Workplace";
  if (cls.includes("Building.Stores")) return "Store";
  if (cls.includes("Building.Houses")) return "House";
  if (cls.includes("FruitTrees")) return "FruitTree";
  if (cls.includes("Statues")) return "Decoration";
  if (cls.includes("Animals")) return "Animal";
  if (cls.includes("Decorations")) return "Gift";
  if (cls.endsWith("CastleItem")) return "Church";
  if (cls.includes("Tower")) return "Tower";
  if (cls.endsWith("BridgeAngelItem")) return "BridgeGhost";
  if (/GemStoreItem|WoodStoreItem|GoldStoreItem/.test(cls)) return "BankTrade";
  return "Character";
};

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\s+/g, " ");

const rows = [];
for (const m of items.matchAll(/<store name="([^"]+)">([\s\S]*?)<\/store>/g)) {
  const [, rawName, b] = m;
  const name = rename(rawName);
  const cls = tag(b, "itemclass");
  rows.push(`            new StoreItemDef("${esc(name)}", ${+tag(b, "id")}, ${+tag(b, "costwood")}, ${+tag(b, "costrock")}, ${+tag(b, "costgem")}, ` +
    `${+tag(b, "inner")}f, ${+tag(b, "outer")}f, ${+tag(b, "max")}, StoreItemKind.${kindOf(cls, rawName)}, "${esc(cls)}",\n` +
    `                "${esc(rename(tag(b, "description")))}"),`);
}

const storesBlock = tag(game, "stores");
const lists = [];
for (const m of storesBlock.matchAll(/<(\w+)>([\s\S]*?)<\/\1>/g)) {
  const names = [...m[2].matchAll(/<item>([^<]+)<\/item>/g)].map((x) => `"${esc(rename(x[1]))}"`);
  lists.push(`            { "${m[1]}", new[] { ${names.join(", ")} } },`);
}

const out = `// <auto-generated>
// Generated by Tools/data/gen_store_data.mjs from docs/reference/store_items.xml and game.xml.
// Do not edit by hand: change the XML and re-run the generator.
// </auto-generated>
using System.Collections.Generic;

namespace CapyIsland.Game
{
    public static partial class StoreData
    {
        /// <summary>Every store item, in store_items.xml order.</summary>
        public static readonly StoreItemDef[] All =
        {
${rows.join("\n")}
        };

        /// <summary>Each store's stock, game.xml &lt;stores&gt;, in display order.</summary>
        public static readonly Dictionary<string, string[]> Lists = new()
        {
${lists.join("\n")}
        };
    }
}
`;
fs.writeFileSync("Assets/Scripts/Game/StoreData.g.cs", out);
console.log(`StoreData.g.cs: ${rows.length} items, ${lists.length} store lists`);
