#!/usr/bin/env node
// Generates Assets/Scripts/Game/QuestData.g.cs from docs/reference/save_data.xml: the motes, the
// cards, the ghosts' quests, Coriander's and Pirate Peach's missions and their idle comments.
// Data only. The capybara stands in for the bunni in every line the player reads.
//
// Usage: node Tools/data/gen_quest_data.mjs

import fs from "node:fs";

const xml = fs.readFileSync("docs/reference/save_data.xml", "utf8");
const tag = (block, name) => {
  const m = block.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`));
  return m ? m[1].trim() : "";
};
const all = (block, name) => [...block.matchAll(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`, "g"))].map((m) => m[1].trim());

const rename = (s) => s
  // Touch screens: the original's "click" is a tap here.
  .replace(/\bClicking\b/g, "Tapping")
  .replace(/\bclicking\b/g, "tapping")
  .replace(/\bClick\b/g, "Tap")
  .replace(/\bclick\b/g, "tap")
  .replace(/Bunni House/g, "Capy House")
  .replace(/Bunni Island/g, "Capy Island")
  .replace(/Bunni Islands/g, "Capy Islands")
  .replace(/\bBunnis\b/g, "Capybaras")
  .replace(/\bbunnis\b/g, "capybaras")
  .replace(/\bBunnies\b/g, "Capybaras")
  .replace(/\bbunnies\b/g, "capybaras")
  .replace(/\bBunni\b/g, "Capybara")
  .replace(/\bbunni\b/g, "capybara")
  .replace(/\bBunny\b/g, "Capybara")
  .replace(/\bbunny\b/g, "capybara");

const esc = (s) => rename(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, " ").replace(/\s+/g, " ").trim();
const str = (s) => `"${esc(s)}"`;

const motes = [...xml.matchAll(/<mote name="([^"]+)">([\s\S]*?)<\/mote>/g)].map(([, name, b]) =>
  `            new MoteDef(${str(name)}, ${+tag(b, "id")}, ${str(tag(b, "func"))}, ${str(tag(b, "description"))}),`);

const cards = [...xml.matchAll(/<card name="([^"]+)">([\s\S]*?)<\/card>/g)].map(([, name, b]) =>
  `            new CardDef(${str(name)}, ${+tag(b, "id")}, ${str(tag(b, "description"))}, new[] { ${all(b, "func").map(str).join(", ")} }),`);

const quest = (b, giver) =>
  `            new QuestDef(QuestSource.${giver}, ${+tag(b, "id")}, ${str(tag(b, "intro"))},\n` +
  `                ${str(tag(b, "during"))},\n` +
  `                ${str(tag(b, "complete"))},\n` +
  `                trigger: ${str(tag(b, "trigger_mote"))}, setUp: ${str(tag(b, "set_up"))}, completeMote: ${str(tag(b, "complete_mote"))},\n` +
  `                rewardItem: ${str(tag(b, "reward_item"))}, wood: ${+tag(b, "wood") || 0}, gold: ${+tag(b, "gold") || 0}, gems: ${+tag(b, "gems") || 0}),`;

const ghosts = [...xml.matchAll(/<ghost>([\s\S]*?)<\/ghost>/g)].map(([, b]) => quest(b, "Ghost"));
const coriander = [...xml.matchAll(/<coriander>([\s\S]*?)<\/coriander>/g)].map(([, b]) => quest(b, "Coriander"));
const peach = [...xml.matchAll(/<piratepeach>([\s\S]*?)<\/piratepeach>/g)].map(([, b]) => quest(b, "Peach"));

const comments = (name) => [...xml.matchAll(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`, "g"))]
  .map(([, b]) => `            ${str(tag(b, "comment"))},`);

const out = `// <auto-generated>
// Generated by Tools/data/gen_quest_data.mjs from docs/reference/save_data.xml.
// Do not edit by hand: change the XML and re-run the generator.
// </auto-generated>

namespace CapyIsland.Game
{
    public static partial class QuestData
    {
        public static readonly MoteDef[] Motes =
        {
${motes.join("\n")}
        };

        public static readonly CardDef[] Cards =
        {
${cards.join("\n")}
        };

        public static readonly QuestDef[] Ghosts =
        {
${ghosts.join("\n")}
        };

        /// <summary>Coriander's missions, in the order she gives them.</summary>
        public static readonly QuestDef[] Coriander =
        {
${coriander.join("\n")}
        };

        /// <summary>Pirate Peach's missions, in the order she gives them.</summary>
        public static readonly QuestDef[] Peach =
        {
${peach.join("\n")}
        };

        public static readonly string[] CorianderComments =
        {
${comments("coriander_comment").join("\n")}
        };

        public static readonly string[] PeachComments =
        {
${comments("peach_comment").join("\n")}
        };
    }
}
`;
fs.writeFileSync("Assets/Scripts/Game/QuestData.g.cs", out);
console.log(`QuestData.g.cs: ${motes.length} motes, ${cards.length} cards, ${ghosts.length} ghosts, ${coriander.length} coriander, ${peach.length} peach`);
