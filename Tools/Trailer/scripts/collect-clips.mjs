// Indexes the gameplay recorded in Unity (public/clips/<name>/0000.jpg…, audio.wav, taps.json)
// into src/clips.gen.ts: each clip's frame count and where a finger touched the screen, so the
// edit can show the game's pointing hand.
//
// Usage (from Tools/Trailer): node scripts/collect-clips.mjs

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const trailer = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.join(trailer, 'public/clips');
const clips = {};
for (const name of fs.existsSync(root) ? fs.readdirSync(root).sort() : []) {
	const dir = path.join(root, name);
	if (!fs.statSync(dir).isDirectory()) continue;
	const frames = fs.readdirSync(dir).filter((f) => f.endsWith('.jpg')).length;
	const tapsFile = path.join(dir, 'taps.json');
	const taps = fs.existsSync(tapsFile) ? JSON.parse(fs.readFileSync(tapsFile, 'utf8')).filter((t) => t.frame >= 0) : [];
	clips[name] = {frames, audio: fs.existsSync(path.join(dir, 'audio.wav')), taps};
}

const ts = `// Generated by scripts/collect-clips.mjs. Do not edit.

export type Tap = {frame: number; x: number; y: number};
export type ClipInfo = {frames: number; audio: boolean; taps: Tap[]};

export const CLIPS: Record<string, ClipInfo> = ${JSON.stringify(clips)};
`;
fs.writeFileSync(path.join(trailer, 'src/clips.gen.ts'), ts);
console.log(Object.entries(clips).map(([n, c]) => `${n} ${c.frames}f ${c.taps.length} taps`).join('\n'));
